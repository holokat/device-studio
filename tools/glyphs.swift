// Writes src/glyphs.js: vector outlines (SVG path data, 1000 units per em,
// y down, baseline at 0) for the few strings the screen overlays draw, laid
// out by CoreText so kerning matches the system. Run: swift tools/glyphs.swift
import Foundation
import CoreText

let runs: [(key: String, font: String, text: String)] = [
  ("time", "SFProText-Semibold", "9:41"),
  ("date", "SFProText-Semibold", "Wed Apr 1"),
  ("wordmark", "AvenirNext-Regular", "FARBOUND"),
]

func svg(_ path: CGPath, dx: CGFloat) -> String {
  var d = ""
  func p(_ pt: CGPoint) -> String { String(format: "%.1f %.1f", pt.x + dx, -pt.y) }
  path.applyWithBlock { el in
    let e = el.pointee, pts = e.points
    switch e.type {
    case .moveToPoint: d += "M" + p(pts[0])
    case .addLineToPoint: d += "L" + p(pts[0])
    case .addQuadCurveToPoint: d += "Q" + p(pts[0]) + " " + p(pts[1])
    case .addCurveToPoint: d += "C" + p(pts[0]) + " " + p(pts[1]) + " " + p(pts[2])
    case .closeSubpath: d += "Z"
    @unknown default: break
    }
  }
  return d
}

var out: [String: Any] = [:]
for run in runs {
  let font = CTFontCreateWithName(run.font as CFString, 1000, nil)
  let actual = CTFontCopyPostScriptName(font) as String
  guard actual == run.font else { fputs("missing font \(run.font) (got \(actual))\n", stderr); exit(1) }
  let attr = NSAttributedString(string: run.text, attributes: [kCTFontAttributeName as NSAttributedString.Key: font])
  let line = CTLineCreateWithAttributedString(attr)
  var glyphs: [[String: Any]] = []
  for r in CTLineGetGlyphRuns(line) as! [CTRun] {
    let n = CTRunGetGlyphCount(r)
    var g = [CGGlyph](repeating: 0, count: n), pos = [CGPoint](repeating: .zero, count: n), adv = [CGSize](repeating: .zero, count: n)
    CTRunGetGlyphs(r, CFRange(location: 0, length: n), &g)
    CTRunGetPositions(r, CFRange(location: 0, length: n), &pos)
    CTRunGetAdvances(r, CFRange(location: 0, length: n), &adv)
    for i in 0..<n {
      let d = CTFontCreatePathForGlyph(font, g[i], nil).map { svg($0, dx: 0) } ?? ""
      glyphs.append(["d": d, "x": Double(pos[i].x), "w": Double(adv[i].width)])
    }
  }
  out[run.key] = ["font": run.font, "text": run.text, "advance": CTLineGetTypographicBounds(line, nil, nil, nil),
                  "capHeight": Double(CTFontGetCapHeight(font)), "glyphs": glyphs]
}
let json = try! JSONSerialization.data(withJSONObject: out, options: [.sortedKeys])
let js = "// Generated by tools/glyphs.swift from the macOS system fonts. Do not edit.\nexport const glyphs = " + String(data: json, encoding: .utf8)! + ";\n"
try! js.write(toFile: "src/glyphs.js", atomically: true, encoding: .utf8)
print("wrote src/glyphs.js")
